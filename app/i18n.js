let LANG = "en";
function setLang(l) {
  LANG = STRINGS[l] ? l : "en";
  if (typeof document !== "undefined") document.documentElement.lang = LANG;
  return LANG;
}
function getLang() { return LANG; }
/* The browser's preference, overridable with ?lang=de. */
function pickLang() {
  try {
    const q = new URLSearchParams(location.search).get("lang");
    if (q && STRINGS[q]) return q;
    const nav = (navigator.language || "en").slice(0, 2).toLowerCase();
    return STRINGS[nav] ? nav : "en";
  } catch (e) { return "en"; }
}
function t(key, vars) {
  const s = (STRINGS[LANG] && STRINGS[LANG][key]) !== undefined
    ? STRINGS[LANG][key]
    : (STRINGS.en[key] !== undefined ? STRINGS.en[key] : key);
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined ? m : vars[k]));
}
/* English plural forms written "card(s)" are resolved here rather than in
 * fifty call sites; German uses the same marker where it happens to work and
 * spells the word out where it does not. */
function tn(key, n, vars) {
  const s = t(key, Object.assign({ n }, vars || {}));
  return s.replace(/(\w+)\(s\)/g, (m, w) => (Number(n) === 1 ? w : w + "s"))
          .replace(/(\w+)\(en\)/g, (m, w) => (Number(n) === 1 ? w : w + "en"))
          .replace(/(\w+)\(er\)/g, (m, w) => (Number(n) === 1 ? w : w + "er"));
}

